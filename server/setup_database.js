const { pool } = require('./src/config/database');

async function setup() {
  console.log('Aligning public schema tables...');

  // 1. Student (Add auto-increment to student_id since user schema had BIGINT PRIMARY KEY without identity)
  await pool.query(`
    CREATE SEQUENCE IF NOT EXISTS public.student_id_seq START 1;
    ALTER TABLE public.student ALTER COLUMN student_id SET DEFAULT nextval('public.student_id_seq');
    ALTER TABLE public.student ADD COLUMN IF NOT EXISTS password_hash VARCHAR(255);
    ALTER TABLE public.student ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
  `);
  console.log('  ✓ student updated');

  // 4. Scholarship (Add deadline and created_at needed by website)
  await pool.query(`
    ALTER TABLE public.scholarship ADD COLUMN IF NOT EXISTS deadline DATE DEFAULT '2027-05-31';
    ALTER TABLE public.scholarship ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
  `);
  console.log('  ✓ scholarship updated');

  // 5. Eligibility Criteria (Add unique constraint on scholarship_id if not present)
  await pool.query(`
    DO $$ BEGIN
      IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'unique_eligibility_criteria_scholarship'
      ) THEN
        ALTER TABLE public.eligibility_criteria ADD CONSTRAINT unique_eligibility_criteria_scholarship UNIQUE (scholarship_id);
      END IF;
    END $$;
  `);
  console.log('  ✓ eligibility_criteria updated');

  // 7. Reviewer (Add password & status needed for portal login)
  await pool.query(`
    ALTER TABLE public.reviewer ADD COLUMN IF NOT EXISTS password VARCHAR(255);
    ALTER TABLE public.reviewer ADD COLUMN IF NOT EXISTS password_hash VARCHAR(255);
    ALTER TABLE public.reviewer ADD COLUMN IF NOT EXISTS status VARCHAR(30) DEFAULT 'ACTIVE';
    ALTER TABLE public.reviewer ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
  `);
  console.log('  ✓ reviewer updated');

  // 8. Grant Record (Ensure created_at exists)
  await pool.query(`
    ALTER TABLE public.grant_record ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
  `);
  console.log('  ✓ grant_record updated');

  // 9. Application (Add statement, sop for application wizard)
  await pool.query(`
    ALTER TABLE public.application ADD COLUMN IF NOT EXISTS statement TEXT;
    ALTER TABLE public.application ADD COLUMN IF NOT EXISTS sop TEXT;
    DO $$ BEGIN
      IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'unique_student_scholarship_application'
      ) THEN
        ALTER TABLE public.application ADD CONSTRAINT unique_student_scholarship_application UNIQUE (student_id, scholarship_id);
      END IF;
    END $$;
  `);
  console.log('  ✓ application updated');

  // 10. Application Status History (Add changed_by)
  await pool.query(`
    ALTER TABLE public.application_status ADD COLUMN IF NOT EXISTS changed_by VARCHAR(100) DEFAULT 'STUDENT';
  `);
  console.log('  ✓ application_status updated');

  // 11. Application Document (Add file storage fields for document upload)
  await pool.query(`
    ALTER TABLE public.application_document ADD COLUMN IF NOT EXISTS document_path VARCHAR(500);
    ALTER TABLE public.application_document ADD COLUMN IF NOT EXISTS original_name VARCHAR(300);
    ALTER TABLE public.application_document ADD COLUMN IF NOT EXISTS mime_type VARCHAR(100);
    ALTER TABLE public.application_document ADD COLUMN IF NOT EXISTS file_size BIGINT;
    ALTER TABLE public.application_document ADD COLUMN IF NOT EXISTS verified_by BIGINT REFERENCES public.reviewer(reviewer_id);
    ALTER TABLE public.application_document ADD COLUMN IF NOT EXISTS uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();
  `);
  console.log('  ✓ application_document updated');

  // 12. Payment (Add transaction_reference, payment_status)
  await pool.query(`
    ALTER TABLE public.payment ADD COLUMN IF NOT EXISTS transaction_reference VARCHAR(150);
    ALTER TABLE public.payment ADD COLUMN IF NOT EXISTS transaction_id VARCHAR(150);
    ALTER TABLE public.payment ADD COLUMN IF NOT EXISTS payment_status VARCHAR(30) DEFAULT 'PENDING';
  `);
  console.log('  ✓ payment updated');

  // 13. Admin (For Administrator portal login)
  await pool.query(`
    CREATE TABLE IF NOT EXISTS public.admin (
      admin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name VARCHAR(150) NOT NULL,
      email VARCHAR(150) UNIQUE NOT NULL,
      password VARCHAR(255) NOT NULL,
      password_hash VARCHAR(255) NOT NULL,
      role VARCHAR(50) DEFAULT 'ADMIN',
      created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
    );
  `);
  console.log('  ✓ admin table ready');

  // 14. Notification (For student dashboard notifications)
  await pool.query(`
    CREATE TABLE IF NOT EXISTS public.notification (
      notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id BIGINT NOT NULL REFERENCES public.student(student_id) ON DELETE CASCADE,
      title VARCHAR(200) NOT NULL,
      message TEXT NOT NULL,
      type VARCHAR(30) DEFAULT 'INFO',
      is_read BOOLEAN DEFAULT FALSE,
      reference_type VARCHAR(50),
      reference_id BIGINT,
      created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
    );
  `);
  console.log('  ✓ notification table ready');

  console.log('\n✓ All public schema tables successfully updated with website integration columns!');
  await pool.end();
}

setup().catch(err => {
  console.error('Setup failed:', err);
  process.exit(1);
});
